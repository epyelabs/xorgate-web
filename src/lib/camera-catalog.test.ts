import { existsSync, readFileSync } from "node:fs"
import { resolve } from "node:path"
import { describe, expect, it } from "vitest"
import rawCatalog from "@/lib/camera-catalog.json"
import contract from "@/lib/config-contract.json"
import {
  CAMERA_CATALOG,
  CAMERA_CATALOG_SCHEMA_VERSION,
  agentPredatesSensor,
  cameraPresetProblem,
  cameraSensor,
  cameraSensorByDetectedName,
  cameraSensorHints,
  cameraSensorLabel,
  cameraSensorsMinAgent,
  formatCameraOptionValue,
  parseCameraCatalog,
  parseSemver,
} from "./camera-catalog"

// The console's reader of `camera-catalog.json` (plans/support-other-camera-
// models). The file is generated by the backend and vendored; what is tested
// here is the compatibility rule every consumer is held to, because a catalog
// from a NEWER backend must degrade to "this entry is not offered", never to a
// crashed settings page or a guessed-at sensor.

// Overridable so a worktree can be checked against the backend BRANCH that
// generated its copy while that branch is unmerged (see config-contract.test).
const BACKEND_DIR =
  process.env.XORGATE_BACKEND_DIR ??
  resolve(__dirname, "../../../../backend/xorgate-core-service")
const BACKEND_COPY = resolve(
  BACKEND_DIR,
  "src/camera-catalog/camera-catalog.json"
)

/** A minimal valid entry; tests override one field at a time. */
function sensor(
  overrides: Record<string, unknown> = {}
): Record<string, unknown> {
  return {
    id: "imx111",
    label: "Test IMX111",
    tier: "supported",
    minAgent: "0.2.0",
    overlay: {
      name: "imx111",
      fixedParams: [],
      defaultRotation: 0,
      canFlip: true,
    },
    options: [],
    libcameraNames: ["imx111"],
    dtNodeNames: ["imx111"],
    identity: "chip-id",
    source: { props: [] },
    requires: { os: ["bookworm"], packageSet: null },
    unsupportedPresets: [],
    info: { nativeAspect: "16:9" },
    notes: [],
    ...overrides,
  }
}

const catalog = (sensors: unknown[], extra: Record<string, unknown> = {}) =>
  parseCameraCatalog({
    schemaVersion: 1,
    catalogVersion: 9,
    sensors,
    planned: [],
    ...extra,
  })

describe("camera-catalog.json (the vendored copy)", () => {
  it("is in sync with the backend copy", () => {
    // Skipped in a web-only checkout, and while the backend checkout predates
    // the catalog. The authoritative guard is the backend's own
    // regenerate-and-diff test; this catches a stale or hand-edited copy here.
    if (!existsSync(BACKEND_COPY)) {
      expect(rawCatalog.schemaVersion).toBe(CAMERA_CATALOG_SCHEMA_VERSION)
      return
    }
    expect(JSON.parse(readFileSync(BACKEND_COPY, "utf8"))).toEqual(rawCatalog)
  })

  it("is readable by this build, whole", () => {
    expect(CAMERA_CATALOG.usable).toBe(true)
    expect(CAMERA_CATALOG.catalogVersion).toBe(rawCatalog.catalogVersion)
    // Every selectable entry of the file is offered: none fell to "newer".
    expect(CAMERA_CATALOG.sensors.map((s) => s.id)).toEqual(
      rawCatalog.sensors.map((s) => s.id)
    )
    expect(CAMERA_CATALOG.unavailable).toEqual(
      rawCatalog.planned.map((p) => ({
        id: p.id,
        label: p.label,
        why: "planned",
      }))
    )
  })

  it("never lists the reserved `none` as a sensor", () => {
    expect(cameraSensor("none")).toBeUndefined()
    expect(cameraSensorLabel("none")).toBe("No camera")
  })

  it("names only presets the config contract knows", () => {
    // The warning beside the Quality select is keyed by preset name; a name
    // the contract does not list could never match what a device holds.
    const schema = contract.namespaces.recording.jsonSchema as {
      properties: { video: { properties: { preset: { enum: string[] } } } }
    }
    const presets = schema.properties.video.properties.preset.enum
    for (const s of CAMERA_CATALOG.sensors) {
      for (const u of s.unsupportedPresets) expect(presets).toContain(u.preset)
    }
  })

  it("carries the facts the console acts on for the v1 sensors", () => {
    expect(cameraSensor("imx335")?.canFlip).toBe(false)
    expect(cameraSensor("imx708")?.canFlip).toBe(true)
    expect(cameraSensor("imx290")?.options.map((o) => o.key)).toEqual([
      "clockFrequency",
    ])
    expect(cameraSensor("imx219")?.options).toEqual([])
  })

  it("offers every sensor on both OS releases the catalog names (catalog 4)", () => {
    // Catalog 4 added `trixie` to `requires.os`; an OS release this build did
    // not know would silently move the sensor to "needs a newer console".
    for (const s of rawCatalog.sensors) {
      expect(s.requires.os).toEqual(["bookworm", "trixie"])
      expect(cameraSensor(s.id)?.id).toBe(s.id)
    }
    // The IMX662 is named, never offered.
    expect(cameraSensor("imx662")).toBeUndefined()
    expect(CAMERA_CATALOG.unavailable).toContainEqual({
      id: "imx662",
      label: cameraSensorLabel("imx662"),
      why: "planned",
    })
  })
})

describe("parseCameraCatalog — the compatibility rule", () => {
  it("refuses a schemaVersion it does not know: nothing is offered", () => {
    for (const schemaVersion of [2, 0, "1", undefined]) {
      const parsed = parseCameraCatalog({ schemaVersion, sensors: [sensor()] })
      expect(parsed).toEqual({
        usable: false,
        catalogVersion: null,
        sensors: [],
        unavailable: [],
      })
    }
  })

  it("never throws on something that is not a catalog", () => {
    for (const raw of [null, undefined, 7, "x", [], { schemaVersion: 1 }]) {
      const parsed = parseCameraCatalog(raw)
      expect(parsed.sensors).toEqual([])
    }
    expect(parseCameraCatalog({ schemaVersion: 1 }).usable).toBe(true)
  })

  it("ignores keys it does not know, at every level", () => {
    const parsed = catalog(
      [
        sensor({
          somethingNew: { a: 1 },
          overlay: { name: "imx111", canFlip: false, futureFlag: true },
          options: [
            {
              key: "lanes",
              label: "Lanes",
              description: "d",
              unit: null,
              values: [2, 4],
              default: 2,
              hint: "x",
            },
          ],
        }),
      ],
      { futureTopLevel: [1, 2, 3] }
    )
    expect(parsed.usable).toBe(true)
    expect(parsed.sensors).toHaveLength(1)
    expect(parsed.sensors[0]).toMatchObject({ id: "imx111", canFlip: false })
    expect(parsed.sensors[0].options[0]).toEqual({
      key: "lanes",
      label: "Lanes",
      description: "d",
      unit: null,
      values: [2, 4],
      default: 2,
    })
  })

  it.each<[string, Record<string, unknown>]>([
    ["tier", { tier: "experimental" }],
    ["identity", { identity: "eeprom" }],
    [
      "an OS release",
      { requires: { os: ["bookworm", "forky"], packageSet: null } },
    ],
    ["a nativeAspect", { info: { nativeAspect: "1:1" } }],
  ])(
    "treats an unknown %s as 'this entry is not usable', not a parse failure",
    (_what, bad) => {
      const parsed = catalog([
        sensor(),
        sensor({ id: "imx222", label: "Newer", ...bad }),
      ])
      expect(parsed.usable).toBe(true)
      expect(parsed.sensors.map((s) => s.id)).toEqual(["imx111"])
      expect(parsed.unavailable).toEqual([
        { id: "imx222", label: "Newer", why: "newer" },
      ])
    }
  )

  it("offers a sensor on either known OS release, or both", () => {
    const parsed = catalog([
      sensor({ id: "imx401", requires: { os: ["trixie"], packageSet: null } }),
      sensor({
        id: "imx402",
        requires: { os: ["bookworm", "trixie"], packageSet: "arducam" },
      }),
    ])
    expect(parsed.sensors.map((s) => s.id)).toEqual(["imx401", "imx402"])
    expect(parsed.unavailable).toEqual([])
  })

  it("leaves a sensor to a newer console when it cannot read its overlay or an option", () => {
    const parsed = catalog([
      sensor({ id: "imx301", overlay: { name: "imx301" } }),
      sensor({
        id: "imx302",
        options: [{ key: "lanes", values: "2,4", default: 2 }],
      }),
      sensor({ id: "imx303", options: [{ key: "lanes", values: [2, 4] }] }),
    ])
    expect(parsed.sensors).toEqual([])
    expect(parsed.unavailable.map((s) => [s.id, s.why])).toEqual([
      ["imx301", "newer"],
      ["imx302", "newer"],
      ["imx303", "newer"],
    ])
  })

  it("skips entries with no usable id, the reserved id, and duplicates", () => {
    const parsed = catalog([
      "not an object",
      sensor({ id: 7 }),
      sensor({ id: "NOT-AN-ID" }),
      sensor({ id: "none" }),
      sensor(),
      sensor({ label: "Duplicate" }),
    ])
    expect(parsed.sensors.map((s) => s.label)).toEqual(["Test IMX111"])
    expect(parsed.unavailable).toEqual([])
  })

  it("lists planned sensors as named but not selectable", () => {
    const parsed = catalog([sensor()], {
      planned: [
        { id: "imx662", label: "Sony IMX662", tier: "planned" },
        { id: "imx111" },
        5,
      ],
    })
    expect(parsed.sensors.map((s) => s.id)).toEqual(["imx111"])
    expect(parsed.unavailable).toEqual([
      { id: "imx662", label: "Sony IMX662", why: "planned" },
    ])
    expect(cameraSensor("imx662", parsed)).toBeUndefined()
    expect(cameraSensorLabel("imx662", parsed)).toBe("Sony IMX662")
  })

  it("keeps only well-formed unsupported presets", () => {
    const parsed = catalog([
      sensor({
        unsupportedPresets: [
          { preset: "1080p30-4mbps", reason: "Too fast." },
          { preset: 5 },
          "x",
        ],
      }),
    ])
    expect(parsed.sensors[0].unsupportedPresets).toEqual([
      { preset: "1080p30-4mbps", reason: "Too fast." },
    ])
  })
})

describe("lookups", () => {
  it("finds a sensor by what a device reported", () => {
    expect(cameraSensorByDetectedName("imx708_wide_noir")?.id).toBe("imx708")
    expect(cameraSensorByDetectedName("imx708@1a")?.id).toBe("imx708")
    expect(
      cameraSensorByDetectedName("/base/soc/i2c0mux/i2c@0/imx219@10")?.id
    ).toBe("imx219")
    expect(cameraSensorByDetectedName("ov5647")).toBeUndefined()
    for (const junk of [null, undefined, 7, "", {}]) {
      expect(cameraSensorByDetectedName(junk)).toBeUndefined()
      expect(cameraSensor(junk)).toBeUndefined()
    }
  })

  it("labels an id it does not know with the id itself", () => {
    expect(cameraSensorLabel("imx999")).toBe("imx999")
    expect(cameraSensorLabel("imx708")).toBe("Sony IMX708 (Camera Module 3)")
  })

  it("hints what an operator should know before choosing a sensor", () => {
    expect(cameraSensorHints(cameraSensor("imx290")!)).toEqual([])
    expect(cameraSensorHints(cameraSensor("imx335")!)).toEqual([
      "needs extra packages",
      "cannot be rotated",
    ])
  })

  it("warns about a preset only where the catalog says so, in its words", () => {
    const reason = cameraPresetProblem("imx335", "1080p30-4mbps")
    expect(reason).toBe(
      rawCatalog.sensors.find((s) => s.id === "imx335")!.unsupportedPresets[0]
        .reason
    )
    expect(cameraPresetProblem("imx335", "720p15-1mbps")).toBeNull()
    expect(cameraPresetProblem("imx290", "1080p30-4mbps")).toBeNull()
    // A sensor this build does not know is not judged.
    expect(cameraPresetProblem("imx999", "1080p30-4mbps")).toBeNull()
    expect(cameraPresetProblem(undefined, "1080p30-4mbps")).toBeNull()
    expect(cameraPresetProblem("imx335", undefined)).toBeNull()
  })

  it("formats option values in the unit an operator reads", () => {
    const clock = cameraSensor("imx290")!.options[0]
    expect(formatCameraOptionValue(clock, 37125000)).toBe("37.125 MHz")
    expect(formatCameraOptionValue(clock, 74250000)).toBe("74.25 MHz")
    expect(formatCameraOptionValue({ ...clock, unit: "Hz" }, 32768)).toBe(
      "32.768 kHz"
    )
    expect(formatCameraOptionValue({ ...clock, unit: "lanes" }, 4)).toBe(
      "4 lanes"
    )
    expect(formatCameraOptionValue({ ...clock, unit: null }, 4)).toBe("4")
  })
})

describe("agent versions", () => {
  it("parses a semver, with or without a leading v", () => {
    expect(parseSemver("0.2.0")).toEqual([0, 2, 0])
    expect(parseSemver("v1.10.3")).toEqual([1, 10, 3])
    expect(parseSemver("0.2.0-rc1")).toEqual([0, 2, 0])
    // The Rust agent's own report: version, then build sha and channel.
    expect(parseSemver("0.2.1 (bb9aa30, dev)")).toEqual([0, 2, 1])
    expect(parseSemver("v0.2.1 (bb9aa30, dev)")).toEqual([0, 2, 1])
    expect(parseSemver("  v0.2.0\n")).toEqual([0, 2, 0])
    for (const not of ["c92d4f4", "0.2", "1.2.3.4", "", null, undefined, 7]) {
      expect(parseSemver(not)).toBeNull()
    }
  })

  it("names the lowest minAgent in the catalog, as the backend's refusal does", () => {
    expect(cameraSensorsMinAgent()).toBe("0.2.0")
    const two = catalog([
      sensor({ minAgent: "0.10.0" }),
      sensor({ id: "imx222", minAgent: "0.3.1" }),
    ])
    expect(cameraSensorsMinAgent(two)).toBe("0.3.1")
    // An empty or unreadable catalog still answers with the working value.
    expect(cameraSensorsMinAgent(parseCameraCatalog(null))).toBe("0.2.0")
  })

  it("disables a sensor only for a build it KNOWS to be older", () => {
    const [s] = catalog([sensor({ minAgent: "0.3.0" })]).sensors
    expect(agentPredatesSensor(s, "v0.2.0")).toBe(true)
    expect(agentPredatesSensor(s, "0.3.0")).toBe(false)
    expect(agentPredatesSensor(s, "v0.10.0")).toBe(false)
    expect(agentPredatesSensor(s, "0.2.1 (bb9aa30, dev)")).toBe(true)
    expect(agentPredatesSensor(s, "v0.3.0 (bb9aa30, dev)")).toBe(false)
    // Against the shipped catalog (every minAgent 0.2.0).
    for (const real of CAMERA_CATALOG.sensors) {
      expect(agentPredatesSensor(real, "v0.2.0")).toBe(false)
      expect(agentPredatesSensor(real, "0.2.1 (bb9aa30, dev)")).toBe(false)
      expect(agentPredatesSensor(real, "v0.1.1")).toBe(true)
    }
    // A CI sha has no order, and no report says nothing: left to the device.
    expect(agentPredatesSensor(s, "c92d4f4")).toBe(false)
    expect(agentPredatesSensor(s, null)).toBe(false)
  })
})
