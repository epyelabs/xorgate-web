// The served catalog names icons as kebab-case lucide names (`ui.icon`). A
// hand-written map (instead of lucide's full dynamic registry) keeps the icons
// tree-shakeable; unknown names fall back to the node group's icon. Extend as
// the catalog grows.
const ICONS: Record<string, LucideIcon> = {
  activity: Activity,
  "align-horizontal-justify-center": AlignHorizontalJustifyCenter,
  "audio-waveform": AudioWaveform,
  clapperboard: Clapperboard,
  database: Database,
  "file-spreadsheet": FileSpreadsheet,
  "file-video": FileVideo,
  film: Film,
  filter: Filter,
  gauge: Gauge,
  "git-branch": GitBranch,
  "git-merge": GitMerge,
  history: History,
  layers: Layers,
  map: Map,
  "map-pin": MapPin,
  "monitor-play": MonitorPlay,
  plug: Plug,
  puzzle: Puzzle,
  radio: Radio,
  ruler: Ruler,
  scale: Scale,
  scaling: Scaling,
  "scan-eye": ScanEye,
  shapes: Shapes,
  sigma: Sigma,
  "sliders-horizontal": SlidersHorizontal,
  timer: Timer,
  "timer-reset": TimerReset,
  "trending-up": TrendingUp,
  video: Video,
  webcam: Webcam,
  zap: Zap,
}

export function catalogIcon(name: string | undefined): LucideIcon | undefined {
  return name ? ICONS[name] : undefined
}
